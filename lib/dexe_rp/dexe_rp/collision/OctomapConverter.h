class OctomapConverter {
public:
    /**
     * @brief Convert octomap::Pointcloud to octomap::OcTree with given resolution
     */
    inline static std::shared_ptr<octomap::OcTree> ConvertPointCloudToOcTree(const octomap::Pointcloud& pointcloud,
                                                                             double resolution) {
        auto octree = std::make_shared<octomap::OcTree>(resolution);
        for (size_t i = 0; i < pointcloud.size(); ++i) {
            const auto& point = pointcloud.getPoint(i);
            octree->updateNode(octomap::point3d(point(0), point(1), point(2)), true);
        }
        octree->updateInnerOccupancy();
        return octree;
    }

    /**
     * @brief Convert octomap::Pointcloud to octomap::OcTree with given resolution and sensor origin
     *
     * @note sensor_origin is the ray-casting origin in the point cloud frame. Voxels between
     *       sensor_origin and each point are updated as free, while endpoint voxels are
     *       updated as occupied. This means previously occupied voxels on visible paths can be cleared if they are
     *       observed as free by the current scan.
     */
    inline static std::shared_ptr<octomap::OcTree> ConvertPointCloudToOcTree(const octomap::Pointcloud& pointcloud,
                                                                             const octomap::point3d& sensor_origin,
                                                                             double resolution) {
        auto octree = std::make_shared<octomap::OcTree>(resolution);
        octree->insertPointCloud(pointcloud, sensor_origin, -1.0, true, false);
        octree->updateInnerOccupancy();
        return octree;
    }

    /**
     * @brief Convert a list of 3D points to octomap::OcTree with given resolution
     */
    inline static std::shared_ptr<octomap::OcTree> ConvertPointsToOcTree(const std::vector<CVec3d>& points,
                                                                         double resolution) {
        octomap::Pointcloud pointcloud;
        FillPointCloud(points, pointcloud);
        return ConvertPointCloudToOcTree(pointcloud, resolution);
    }

    /**
     * @brief Convert a list of 3D points to octomap::OcTree with given resolution and sensor origin
     */
    inline static std::shared_ptr<octomap::OcTree> ConvertPointsToOcTree(const std::vector<CVec3d>& points,
                                                                         const CVec3d& sensor_origin,
                                                                         double resolution) {
        octomap::Pointcloud pointcloud;
        FillPointCloud(points, pointcloud);
        return ConvertPointCloudToOcTree(
            pointcloud, octomap::point3d(sensor_origin(0), sensor_origin(1), sensor_origin(2)), resolution);
    }

    /**
     * @brief Convert Eigen matrix of 3D points with shape (N, 3) to octomap::OcTree with given resolution
     */
    inline static std::shared_ptr<octomap::OcTree> ConvertPointsToOcTree(const Eigen::Ref<const MatXd>& points,
                                                                         double resolution) {
        octomap::Pointcloud pointcloud;
        FillPointCloud(points, pointcloud);
        return ConvertPointCloudToOcTree(pointcloud, resolution);
    }

    /**
     * @brief Convert Eigen matrix of 3D points with shape (N, 3) to octomap::OcTree with given resolution and sensor
     * origin
     */
    inline static std::shared_ptr<octomap::OcTree> ConvertPointsToOcTree(const Eigen::Ref<const MatXd>& points,
                                                                         const CVec3d& sensor_origin,
                                                                         double resolution) {
        octomap::Pointcloud pointcloud;
        FillPointCloud(points, pointcloud);
        return ConvertPointCloudToOcTree(
            pointcloud, octomap::point3d(sensor_origin(0), sensor_origin(1), sensor_origin(2)), resolution);
    }

    /**
     * @brief Convert a PLY file(no faces) to octomap::OcTree with given resolution
     */
    // Generated by ChatGPT
    inline static std::shared_ptr<octomap::OcTree> ConvertPlyFileToOcTree(const std::string& ply_file_path,
                                                                          double resolution) {
        auto octree = std::make_shared<octomap::OcTree>(resolution);

        std::ifstream in(ply_file_path, std::ios::binary);
        if (!in.is_open()) {
            DEXERP_ERROR("Failed to open PLY file '{}'.", ply_file_path);
            return octree;
        }

        PlyFormat format = PlyFormat::Unknown;
        size_t vertex_count = 0;
        std::vector<PlyProperty> props;
        bool in_vertex = false;

        std::string line;
        while (std::getline(in, line)) {
            if (line == "ply") continue;
            if (line.rfind("format ", 0) == 0) {
                if (line.find("ascii") != std::string::npos)
                    format = PlyFormat::Ascii;
                else if (line.find("binary_little_endian") != std::string::npos)
                    format = PlyFormat::BinaryLE;
                else if (line.find("binary_big_endian") != std::string::npos)
                    format = PlyFormat::BinaryBE;
            } else if (line.rfind("element ", 0) == 0) {
                std::istringstream iss(line);
                std::string _, name;
                iss >> _ >> name;
                in_vertex = (name == "vertex");
                if (in_vertex) iss >> vertex_count;
            } else if (in_vertex && line.rfind("property ", 0) == 0) {
                std::istringstream iss(line);
                std::string _, type, name;
                iss >> _ >> type >> name;
                props.push_back({name, type});
            } else if (line == "end_header") {
                break;
            }
        }

        auto find_idx = [&](const std::string& name) {
            for (size_t i = 0; i < props.size(); ++i)
                if (props[i].name == name) return static_cast<int>(i);
            return -1;
        };

        const int x_idx = find_idx("x");
        const int y_idx = find_idx("y");
        const int z_idx = find_idx("z");
        if (x_idx < 0 || y_idx < 0 || z_idx < 0) {
            DEXERP_ERROR("PLY file '{}' has no x/y/z vertex properties.", ply_file_path);
            return octree;
        }

        const bool host_little_endian = ([] {
            uint16_t v = 1;
            return *reinterpret_cast<uint8_t*>(&v) == 1;
        })();
        const bool file_little_endian = (format != PlyFormat::BinaryBE);
        const bool swap_endian = (format != PlyFormat::Ascii) && (host_little_endian != file_little_endian);

        for (size_t i = 0; i < vertex_count; ++i) {
            double x = 0, y = 0, z = 0;

            if (format == PlyFormat::Ascii) {
                std::getline(in, line);
                std::istringstream iss(line);
                for (size_t j = 0; j < props.size(); ++j) {
                    double v = 0;
                    iss >> v;
                    if (static_cast<int>(j) == x_idx) x = v;
                    if (static_cast<int>(j) == y_idx) y = v;
                    if (static_cast<int>(j) == z_idx) z = v;
                }
            } else {
                for (size_t j = 0; j < props.size(); ++j) {
                    double v = ReadBinaryScalar(in, props[j].type, swap_endian);
                    if (static_cast<int>(j) == x_idx) x = v;
                    if (static_cast<int>(j) == y_idx) y = v;
                    if (static_cast<int>(j) == z_idx) z = v;
                }
            }

            octree->updateNode(octomap::point3d(static_cast<float>(x), static_cast<float>(y), static_cast<float>(z)),
                               true);
        }

        octree->updateInnerOccupancy();
        return octree;
    }
    // End of ChatGPT generated code

private:
    // Generated by ChatGPT
    enum class PlyFormat { Ascii, BinaryLE, BinaryBE, Unknown };

    struct PlyProperty {
        std::string name;
        std::string type;
    };

    inline static size_t PlyTypeSize(const std::string& type) {
        if (type == "char" || type == "uchar" || type == "int8" || type == "uint8") return 1;
        if (type == "short" || type == "ushort" || type == "int16" || type == "uint16") return 2;
        if (type == "int" || type == "uint" || type == "float" || type == "int32" || type == "uint32") return 4;
        if (type == "double" || type == "int64" || type == "uint64") return 8;
        throw std::runtime_error("Unsupported PLY type: " + type);
    }

    template <typename T>
    inline static T ByteSwap(T value) {
        std::array<std::byte, sizeof(T)> src{}, dst{};
        std::memcpy(src.data(), &value, sizeof(T));
        std::reverse_copy(src.begin(), src.end(), dst.begin());
        std::memcpy(&value, dst.data(), sizeof(T));
        return value;
    }

    inline static double ReadBinaryScalar(std::ifstream& in, const std::string& type, bool swap_endian) {
        auto read_value = [&](auto dummy) -> double {
            using T = decltype(dummy);
            T v{};
            in.read(reinterpret_cast<char*>(&v), sizeof(T));
            if (swap_endian && sizeof(T) > 1) v = ByteSwap(v);
            return static_cast<double>(v);
        };

        if (type == "char" || type == "int8") return read_value(int8_t{});
        if (type == "uchar" || type == "uint8") return read_value(uint8_t{});
        if (type == "short" || type == "int16") return read_value(int16_t{});
        if (type == "ushort" || type == "uint16") return read_value(uint16_t{});
        if (type == "int" || type == "int32") return read_value(int32_t{});
        if (type == "uint" || type == "uint32") return read_value(uint32_t{});
        if (type == "float") return read_value(float{});
        if (type == "double") return read_value(double{});
        throw std::runtime_error("Unsupported PLY type: " + type);
    }
    // End of ChatGPT generated code

    inline static void FillPointCloud(const Eigen::Ref<const MatXd>& points, octomap::Pointcloud& pointcloud) {
        if (points.cols() != 3) {
            throw std::invalid_argument("points must have shape (N, 3)");
        }

        pointcloud.reserve(static_cast<unsigned int>(points.rows()));
        for (Eigen::Index i = 0; i < points.rows(); ++i) {
            pointcloud.push_back(static_cast<float>(points(i, 0)), static_cast<float>(points(i, 1)),
                                 static_cast<float>(points(i, 2)));
        }
    }

    inline static void FillPointCloud(const std::vector<CVec3d>& points, octomap::Pointcloud& pointcloud) {
        pointcloud.reserve(static_cast<unsigned int>(points.size()));
        for (const auto& p : points) {
            pointcloud.push_back(static_cast<float>(p(0)), static_cast<float>(p(1)), static_cast<float>(p(2)));
        }
    }
};
