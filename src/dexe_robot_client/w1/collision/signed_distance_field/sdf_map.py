"""
[IMPORTANT] The following code is generated by AI and havn't been detailedly reviewed by human.[IMPORTANT]

Dense signed-distance maps for collision costs in numerical IK.

The stored convention is the common level-set convention:

* negative inside the obstacle
* zero on the surface
* positive outside the obstacle

The grid lives directly in the mesh/OBJ coordinate frame.  Online queries use
trilinear interpolation.  Queries outside the map are never extrapolated from
the lookup table; they are extended from the map AABB with a conservative,
continuous distance lower bound.
"""

