def run_self_test() -> None:
    rng = np.random.default_rng(42)
    theta_true = np.array([0.018, 0.026, 0.031, 0.002, -0.003, 0.004])
    inertia_true = theta_to_inertia_matrix(theta_true)
    omega = rng.normal(size=(240, 3))
    alpha = rng.normal(size=(240, 3))
    torque = np.vstack([inertia_true @ alpha[i] + np.cross(omega[i], inertia_true @ omega[i]) for i in range(omega.shape[0])])
    result = fit_inertia_from_rotational_terms(omega, alpha, torque)
    err = np.linalg.norm(np.asarray(result["theta"]) - theta_true)
    print(f"self-test theta_err={err:.6e}, torque_rms={result['torque_rms']:.6e}")
    if err > 1e-10:
        raise RuntimeError("Synthetic inertia self-test failed.")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Identify tool inertia_com from dynamic 6D force sensor data.")
    parser.add_argument("--arm", choices=["primary", "secondary"], default="primary")
    parser.add_argument("--state-topic", default=DEFAULT_STATE_TOPIC)
    parser.add_argument("--input", type=Path, help="Existing JSONL log to fit. If omitted, capture online first.")
    parser.add_argument("--duration", type=float, default=0.0, help="Online capture duration. 0 means stop by Enter.")
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--dt", type=float, default=DEFAULT_DT)
    parser.add_argument("--robot-type", choices=["w1_anth", "w1_indst"], default="w1_anth")
    parser.add_argument("--mass", type=float, required=True, help="Tool mass in kg, stored for diagnostics.")
    parser.add_argument("--com-mm", required=True, help="Tool COM in flange/EE frame, mm: x,y,z")
    parser.add_argument("--w-bias", required=True, help="Sensor zero bias in raw_sri order, same format as tool_com_estimate.py w_bias.")
    parser.add_argument(
        "--wrench-format",
        choices=["raw_sri", "state_mapped"],
        default="raw_sri",
        help="Use raw_sri/raw_force_sensor by default to avoid already compensated wrench data.",
    )
    parser.add_argument("--trim-start", type=float, default=1.0)
    parser.add_argument("--trim-end", type=float, default=1.0)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        return args
    if args.dt <= 0.0:
        parser.error("--dt must be positive.")
    if args.mass <= 0.0:
        parser.error("--mass must be positive.")
    parse_float_list(args.com_mm, 3, "--com-mm")
    parse_float_list(args.w_bias, 6, "--w-bias")
    return args


def main() -> None:
    args = parse_args()
    if args.self_test:
        run_self_test()
        return

    if args.input:
        samples = samples_from_jsonl(args.input.expanduser(), args.arm, args.wrench_format)
        capture_path = args.input.expanduser()
    else:
        samples = capture_online(args)
        capture_path = args.output_dir / f"tool_inertia_capture_{datetime.now().strftime('%Y%m%d_%H%M%S')}.jsonl"
        write_jsonl(capture_path, samples)
        print(f"采集数据已保存: {capture_path}")

    com_m = parse_float_list(args.com_mm, 3, "--com-mm") / 1000.0
    w_bias_raw = parse_float_list(args.w_bias, 6, "--w-bias")
    w_bias_ee = map_raw_sri_bias_to_ee(w_bias_raw) if args.wrench_format == "raw_sri" else w_bias_raw
    arrays = prepare_fit_arrays(samples, args.arm, args.robot_type, args.dt, com_m, w_bias_ee, args.trim_start, args.trim_end)
